package com.example.data.model

data class ServerProperties(
    val serverPort: Int = 25565,
    val motd: String = "A MobileCraft Minecraft Server",
    val maxPlayers: Int = 10,
    val difficulty: String = "easy", // peaceful, easy, normal, hard
    val gamemode: String = "survival", // survival, creative, adventure, spectator
    val onlineMode: Boolean = false, // false allows offline/LAN play easily on mobile
    val pvp: Boolean = true,
    val allowFlight: Boolean = false,
    val viewDistance: Int = 8,
    val simulationDistance: Int = 6,
    val spawnProtection: Int = 16,
    val whiteList: Boolean = false,
    val enableCommandBlock: Boolean = true,
    val allowNether: Boolean = true,
    val generateStructures: Boolean = true,
    val levelType: String = "minecraft:normal",
    val rawProperties: Map<String, String> = emptyMap()
) {
    companion object {
        fun parse(content: String): ServerProperties {
            val map = mutableMapOf<String, String>()
            content.lineSequence().forEach { line ->
                val trimmed = line.trim()
                if (trimmed.isNotEmpty() && !trimmed.startsWith("#")) {
                    val splitIdx = trimmed.indexOf('=')
                    if (splitIdx != -1) {
                        val key = trimmed.substring(0, splitIdx).trim()
                        val value = trimmed.substring(splitIdx + 1).trim()
                        map[key] = value
                    }
                }
            }

            return ServerProperties(
                serverPort = map["server-port"]?.toIntOrNull() ?: 25565,
                motd = map["motd"] ?: "A MobileCraft Minecraft Server",
                maxPlayers = map["max-players"]?.toIntOrNull() ?: 10,
                difficulty = map["difficulty"] ?: "easy",
                gamemode = map["gamemode"] ?: "survival",
                onlineMode = map["online-mode"]?.toBooleanStrictOrNull() ?: false,
                pvp = map["pvp"]?.toBooleanStrictOrNull() ?: true,
                allowFlight = map["allow-flight"]?.toBooleanStrictOrNull() ?: false,
                viewDistance = map["view-distance"]?.toIntOrNull() ?: 8,
                simulationDistance = map["simulation-distance"]?.toIntOrNull() ?: 6,
                spawnProtection = map["spawn-protection"]?.toIntOrNull() ?: 16,
                whiteList = map["white-list"]?.toBooleanStrictOrNull() ?: false,
                enableCommandBlock = map["enable-command-block"]?.toBooleanStrictOrNull() ?: true,
                allowNether = map["allow-nether"]?.toBooleanStrictOrNull() ?: true,
                generateStructures = map["generate-structures"]?.toBooleanStrictOrNull() ?: true,
                levelType = map["level-type"] ?: "minecraft:normal",
                rawProperties = map
            )
        }
    }

    fun toPropertiesFileContent(): String {
        val merged = rawProperties.toMutableMap()
        merged["server-port"] = serverPort.toString()
        merged["motd"] = motd
        merged["max-players"] = maxPlayers.toString()
        merged["difficulty"] = difficulty
        merged["gamemode"] = gamemode
        merged["online-mode"] = onlineMode.toString()
        merged["pvp"] = pvp.toString()
        merged["allow-flight"] = allowFlight.toString()
        merged["view-distance"] = viewDistance.toString()
        merged["simulation-distance"] = simulationDistance.toString()
        merged["spawn-protection"] = spawnProtection.toString()
        merged["white-list"] = whiteList.toString()
        merged["enable-command-block"] = enableCommandBlock.toString()
        merged["allow-nether"] = allowNether.toString()
        merged["generate-structures"] = generateStructures.toString()
        merged["level-type"] = levelType

        val sb = StringBuilder()
        sb.appendLine("# Minecraft server properties")
        sb.appendLine("# Generated by MobileCraft Server")
        merged.entries.sortedBy { it.key }.forEach { (k, v) ->
            sb.appendLine("$k=$v")
        }
        return sb.toString()
    }
}
